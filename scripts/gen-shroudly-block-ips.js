#!/usr/bin/env node
'use strict';

/*
 * Generates V2rayNG/app/src/main/assets/shroudly/block-ips.txt
 * from third_party/Shroudly/electron/censor-fingerprints.js
 *
 *   node scripts/gen-shroudly-block-ips.js           write it
 *   node scripts/gen-shroudly-block-ips.js --check   fail if out of date
 */

const fs = require('fs');
const path = require('path');
const { ALL } = require('../third_party/Shroudly/electron/censor-fingerprints');

const out = path.join(__dirname, '..', 'V2rayNG', 'app', 'src', 'main', 'assets', 'shroudly', 'block-ips.txt');
const text = ['# Generated by scripts/gen-shroudly-block-ips.js from third_party/Shroudly/electron/censor-fingerprints.js. Do not edit.',
  ...ALL, ''].join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) {
    console.error('[block-ips] out of date: run node scripts/gen-shroudly-block-ips.js');
    process.exit(1);
  }
  console.log(`[block-ips] up to date (${ALL.length} addresses)`);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`[block-ips] ${ALL.length} addresses written to ${out}`);
}
